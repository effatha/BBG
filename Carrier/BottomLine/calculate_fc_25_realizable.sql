with cte_fc_shares as 
(
	SELECT 
		NUM_ITEM,
		CD_CHANNEL_GROUP_3,
		CD_COUNTRY_GROUP,
		VL_ITEM_QUANTITY = SUM(VL_ITEM_QUANTITY),
		AMT_TOTAL_QUANTITY = SUM(SUM(VL_ITEM_QUANTITY)) over(partition by NUM_ITEM),
		ChannelShare = SUM(VL_ITEM_QUANTITY) / SUM(SUM(VL_ITEM_QUANTITY)) over(partition by NUM_ITEM)
	FROM L1.L1_FACT_F_BOTTOM_LINE_FORECAST
	where 
	NUM_ITEM = '10000164'
	and YEAR(D_TARGET) = 2025
	and MONTH(D_TARGET) = 9
	GROUP BY CD_CHANNEL_GROUP_3,NUM_ITEM,CD_COUNTRY_GROUP

)
SELECT
		NUM_ITEM,
		CD_CHANNEL_GROUP_3,
		CD_COUNTRY_GROUP,
		fc.REALIZABLEFCQTYSEP25,
		VL_ITEM_QUANTITY = REALIZABLEFCQTYSEP25 *ChannelShare ,
		AMT_NET_ORDER_VALUE_EUR = (REALIZABLEFCQTYSEP25 *ChannelShare) * PLANPRICE,
		AMT_PLAN_PRICE_EUR = PLANPRICE
FROM L0.L0_MI_REALIZABLE_FC_25 fc
INNER JOIN cte_fc_shares sh
	on fc.ItemNo = sh.NUM_ITEM





	

