				,AMT_REPACKING_FEE_UNIT_EUR							= (VL_NET_ORDER_QUANTITY_EST - VL_RETURNED_QUANTITY_EST+VL_REPLACEMENT_QUANTITY_EST)*AMT_REPACKING_FEE_PER_UNIT_CALC_EUR

				,AMT_MEK_TO_CUSTOMER_EST_EUR						= CASE WHEN VL_NET_ORDER_QUANTITY_EST <> 0 
																			THEN (((VL_NET_ORDER_QUANTITY_EST) * (ISNULL(AMT_MEK_HEDGING_EUR,0)-ISNULL(AMT_GTS_MARKUP,0)) )/ISNULL(VL_NET_ORDER_QUANTITY_EST,1)) * [VL_NET_QUANTITY_EST_PARAM]  
																		ELSE 0 END	
				,AMT_MEK_FROM_CUSTOMER_EST_EUR						= CASE WHEN VL_NET_ORDER_QUANTITY_EST <> 0 
																			THEN (((VL_RETURNED_QUANTITY_EST) * (ISNULL(AMT_MEK_HEDGING_EUR,0)-ISNULL(AMT_GTS_MARKUP,0)) )/ISNULL(VL_NET_ORDER_QUANTITY_EST,1)) * [VL_NET_QUANTITY_EST_PARAM]  
																		ELSE 0 END	
				,AMT_MEK_REPLACEMENT_EST_EUR						= CASE WHEN VL_NET_ORDER_QUANTITY_EST <> 0 
																			THEN (((VL_REPLACEMENT_QUANTITY_EST) * (ISNULL(AMT_MEK_HEDGING_EUR,0)-ISNULL(AMT_GTS_MARKUP,0)) )/ISNULL(VL_NET_ORDER_QUANTITY_EST,1)) * [VL_NET_QUANTITY_EST_PARAM]  
																		ELSE 0 END
				,AMT_MEK_DEPRECIATION_EST_EUR 						= CASE WHEN VL_NET_ORDER_QUANTITY_EST <> 0 
																			THEN (((VL_RETURNED_QUANTITY_EST * VL_DEPRETIATION_RATE) * (ISNULL(AMT_MEK_HEDGING_EUR,0)-ISNULL(AMT_GTS_MARKUP,0)) )/ISNULL(VL_NET_ORDER_QUANTITY_EST,1)) * [VL_NET_QUANTITY_EST_PARAM]  
																		ELSE 0 END

		FROM CTE_SALES_L4 sales
