				,AMT_REVENUE_EST_EUR								= (ISNULL(AMT_NET_ORDER_VALUE_EST_EUR,0) - ISNULL(AMT_REFUNDED_ORDER_VALUE_EST_EUR,0)) * [VL_REVENUE_EST_PARAM]
				,VL_NET_QUANTITY_EST								= (ISNULL(VL_NET_ORDER_QUANTITY_EST,0) - ISNULL(VL_REFUNDED_QUANTITY_EST,0)) * [VL_NET_QUANTITY_EST_PARAM] 
				,AMT_NET_PRODUCT_COSTS_THEREOF_RETURN_MEK_EUR		= ISNULL(AMT_MEK_HEDGING_EUR,0)	* VL_NET_PRODUCT_COSTS_THEREOF_RETURN_MEK_PARAM		
				,AMT_SHIPPING_COST_INVOICED_EST_EUR 					= (VL_NET_ORDER_QUANTITY_EST * AMT_SHIPPING_COST_EST_EUR) --* ISNULL(AMT_SHIP_CORRECTION_FACTOR_ORDER,1))
				,AMT_SHIPPING_COST_RETURNED_EST_EUR 					= (VL_RETURNED_QUANTITY_EST * AMT_SHIPPING_COST_EST_EUR) --* ISNULL(AMT_SHIP_CORRECTION_FACTOR_RETURN,1))
				,AMT_SHIPPING_COST_REPLACED_EST_EUR 					= (VL_REPLACEMENT_QUANTITY_EST * AMT_SHIPPING_COST_EST_EUR) --* ISNULL(AMT_SHIP_CORRECTION_FACTOR_REPLACEMENT,1))
				,AMT_NET_ORDER_CONTRIBUTION_EST_EUR					= AMT_NET_ORDER_VALUE_EST_EUR - (CASE WHEN VL_NET_ORDER_QUANTITY_EST <> 0 THEN (((VL_NET_ORDER_QUANTITY_EST) * (ISNULL(AMT_MEK_HEDGING_EUR,0)-ISNULL(AMT_GTS_MARKUP,0)) )/ISNULL(VL_NET_ORDER_QUANTITY_EST,1)) * [VL_NET_QUANTITY_EST_PARAM]  ELSE 0 END)
