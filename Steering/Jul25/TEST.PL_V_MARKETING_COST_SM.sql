	TransactionDate = ISNULL(amz.D_CAMPAIGN,ISNULL(ggl.D_CAMPAIGN,d2c.D_CAMPAIGN)),
	ProductFamily = ISNULL(amz.[T_PRODUCT_HIERARCHY_4],ISNULL(ggl.[T_PRODUCT_HIERARCHY_4],d2c.[T_PRODUCT_HIERARCHY_4])),
	ChannelGroup3 = REPLACE(ISNULL(amz.CD_CHANNEL_GROUP_3,ISNULL(ggl.CD_CHANNEL_GROUP_3,d2c.CD_CHANNEL_GROUP_3)),' ',''),
	CountryGroup = ISNULL(amz.CountryGroup,ISNULL(ggl.CountryGroup,d2c.CountryGroup)),
