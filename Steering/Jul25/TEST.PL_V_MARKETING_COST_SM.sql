ALTER VIEW TEST.PL_V_MARKETING_COST_SM_v2
AS
with CTE_MKT_AMAZON AS 
(


SELECT 
	D_CAMPAIGN,
	[T_PRODUCT_HIERARCHY_4],
	CD_CHANNEL_GROUP_3 = channel.CD_CHANNEL_GROUP_3,
	CountryGroup = CASE WHEN acc.CD_COUNTRY in('PL','FR','CZ','HR','IT','GB','NL','RO','HU','ES','BG','DE','SI','SK') THEN acc.CD_COUNTRY
							  WHEN  channel.CD_CHANNEL_GROUP_3 ='CEE' then 'SK' 
							  ELSE 'INT' END,
	MKT_AMT = SUM((ISNULL([AMT_COST_EUR_ATT],0)+ISNULL([GOOGLE_AMT_COST_EUR_ATT],0)+ISNULL([DSP_AMT_COST_EUR_ATT],0))) 
FROM 
[L1].L1_FACT_A_AMAZON_ITEM_ATTRIBUTION amz
INNER JOIN L1.L1_DIM_A_ITEM it on it.ID_ITEM = amz.ID_ITEM
INNER JOIN L1.L1_DIM_A_MARKETING_ACCOUNT acc on acc.[ID_MARKETING_ACCOUNT] = amz.[ID_MARKETING_ACCOUNT]
LEFT JOIN L1.L1_DIM_A_SALES_CHANNEL channel
        on channel.[CD_SALES_CHANNEL] = acc.[CD_SALES_CHANNEL]
WHERE
 YEAR(D_CAMPAIGN) >= 2025 and [T_PRODUCT_HIERARCHY_4] is not null
GROUP BY [T_PRODUCT_HIERARCHY_4],channel.CD_CHANNEL_GROUP_3,D_CAMPAIGN,
CASE WHEN acc.CD_COUNTRY in ('PL','FR','CZ','HR','IT','GB','NL','RO','HU','ES','BG','DE','SI','SK') THEN acc.CD_COUNTRY
							  WHEN  channel.CD_CHANNEL_GROUP_3 ='CEE' then 'SK' 
							  ELSE 'INT' END
HAVING SUM((ISNULL([AMT_COST_EUR_ATT],0)+ISNULL([GOOGLE_AMT_COST_EUR_ATT],0)+ISNULL([DSP_AMT_COST_EUR_ATT],0))) >  0
),
CTE_MKT_GOOGLE AS 
(


SELECT 	D_CAMPAIGN,
	[T_PRODUCT_HIERARCHY_4],
	CD_CHANNEL_GROUP_3 = channel.CD_CHANNEL_GROUP_3,
	CountryGroup = CASE WHEN acc.CD_COUNTRY in('PL','FR','CZ','HR','IT','GB','NL','RO','HU','ES','BG','DE','SI','SK') THEN acc.CD_COUNTRY
							  WHEN  channel.CD_CHANNEL_GROUP_3 ='CEE' then 'SK' 
							  ELSE 'INT' END,
	GGL_AMT = SUM(ISNULL([AMT_COST_EUR_ATT],0)) 
FROM 
[L1].L1_FACT_A_GOOGLE_ITEM_ATTRIBUTION amz
INNER JOIN L1.L1_DIM_A_ITEM it on it.ID_ITEM = amz.ID_ITEM
INNER JOIN L1.L1_DIM_A_MARKETING_ACCOUNT acc on acc.[ID_MARKETING_ACCOUNT] = amz.[ID_MARKETING_ACCOUNT]
LEFT JOIN L1.L1_DIM_A_SALES_CHANNEL channel
        on channel.[CD_SALES_CHANNEL] = acc.[CD_SALES_CHANNEL]
WHERE
 YEAR(D_CAMPAIGN) >= 2025 and [T_PRODUCT_HIERARCHY_4] is not null
GROUP BY [T_PRODUCT_HIERARCHY_4],channel.CD_CHANNEL_GROUP_3,D_CAMPAIGN,
CASE WHEN acc.CD_COUNTRY in ('PL','FR','CZ','HR','IT','GB','NL','RO','HU','ES','BG','DE','SI','SK') THEN acc.CD_COUNTRY
							  WHEN  channel.CD_CHANNEL_GROUP_3 ='CEE' then 'SK' 
							  ELSE 'INT' END
HAVING SUM(ISNULL([AMT_COST_EUR_ATT],0)) > 0 
),
CTE_MKT_D2C AS 
(


SELECT 	D_CAMPAIGN,
	[T_PRODUCT_HIERARCHY_4],
	CD_CHANNEL_GROUP_3 = channel.CD_CHANNEL_GROUP_3,
	CountryGroup = CASE WHEN acc.CD_COUNTRY in('PL','FR','CZ','HR','IT','GB','NL','RO','HU','ES','BG','DE','SI','SK') THEN acc.CD_COUNTRY
							  WHEN  channel.CD_CHANNEL_GROUP_3 ='CEE' then 'SK' 
							  ELSE 'INT' END,
	D2C_AMT = SUM(ISNULL([AMT_COST_EUR_ATT],0)) 
FROM 
[L1].L1_FACT_A_D2C_PERFORMANCE_ITEM amz
INNER JOIN L1.L1_DIM_A_ITEM it on it.ID_ITEM = amz.ID_ITEM
INNER JOIN L1.L1_DIM_A_MARKETING_ACCOUNT acc on acc.[ID_MARKETING_ACCOUNT] = amz.[ID_MARKETING_ACCOUNT]
LEFT JOIN L1.L1_DIM_A_SALES_CHANNEL channel
        on channel.[CD_SALES_CHANNEL] = acc.[CD_SALES_CHANNEL]
WHERE
 YEAR(D_CAMPAIGN) >= 2025 and [T_PRODUCT_HIERARCHY_4] is not null
GROUP BY [T_PRODUCT_HIERARCHY_4],channel.CD_CHANNEL_GROUP_3,D_CAMPAIGN,
CASE WHEN acc.CD_COUNTRY in ('PL','FR','CZ','HR','IT','GB','NL','RO','HU','ES','BG','DE','SI','SK') THEN acc.CD_COUNTRY
							  WHEN  channel.CD_CHANNEL_GROUP_3 ='CEE' then 'SK' 
							  ELSE 'INT' END
HAVING SUM(ISNULL([AMT_COST_EUR_ATT],0)) > 0 

)
